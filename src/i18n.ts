export function tr(language: AppLanguage, text: string): string {
  return language === "en" ? (EN[text] ?? text) : text;
}

export function trCount(language: AppLanguage, count: number, huSingular: string, huPlural = huSingular): string {
  if (language === "en") return `${count} ${EN[huPlural] ?? EN[huSingular] ?? huPlural}`;
  return `${count} ${count === 1 ? huSingular : huPlural}`;
}

export function uiText(text: string): string {
  const language: AppLanguage = typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "hu";
  return tr(language, text);
}
